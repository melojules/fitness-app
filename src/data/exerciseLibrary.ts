// Custom exercises the user creates in the program builder — see uploads/fitness-app-prompt.md §6.
// Kept as a runtime registry alongside the static library so getExercise/getAllExercises see both;
// ProfileProvider persists these and re-registers them on hydrate (see src/state/ProfileContext.tsx).
let customExercises: ExerciseLibraryItem[] = [];

export function replaceCustomExercises(exercises: ExerciseLibraryItem[]) {
  customExercises = [...exercises];
}

export function registerCustomExercise(exercise: ExerciseLibraryItem) {
  customExercises = [...customExercises.filter((e) => e.id !== exercise.id), exercise];
}

export function getExercise(id: string) {
  const exercise = exerciseLibrary.find((e) => e.id === id) ?? customExercises.find((e) => e.id === id);
  if (!exercise) throw new Error(`Unknown exercise id: ${id}`);
  return exercise;
}

export function getAllExercises() {
  return [...exerciseLibrary, ...customExercises];
}
